"""
Tag every set in the Transmog window's Sets tab with the expansion it belongs to, so the Unbound addon can hide
the sets of expansions that aren't released yet (Unbound.ExpansionUnlocked).

The sets come from mod-transmog-plus's addon (addon/Transmog/features/set_data.lua). Its own "expansion" label
can't be used alone: the PvP sets are all labelled "PVP" whatever their expansion, and a few level 70 and 80
PvP sets are labelled "CLASSIC" or "TBC". So a set belongs to the latest expansion any of its pieces needs, by
the piece's required level (60 or less classic, 61-70 The Burning Crusade, above 70 Wrath of the Lich King),
and never to an earlier expansion than its label says. Required level, not unbound_item_expansion: many level
70 and 80 PvP pieces are sold by vendors in classic cities, which makes them classic there.

Writes addon/Unbound/TransmogSetExpansions.lua (only the sets past classic; a set not listed is classic). Run it
again (with the worldserver's database running) after mod-transmog-plus is updated; the result is committed,
so others don't need to run it:

  python tools/transmog_set_expansions.py [--mysql <mysql.exe>] [--sets <set_data.lua>]
"""
import argparse
import os
import re
import subprocess

HERE = os.path.dirname(os.path.abspath(__file__))
MODULE = os.path.dirname(HERE)
ACORE = os.path.dirname(os.path.dirname(MODULE))
ROOT = os.path.dirname(ACORE)

SET_DATA = os.path.join(ACORE, 'modules', 'mod-transmog-plus', 'addon', 'Transmog', 'features', 'set_data.lua')
OUTPUT = os.path.join(MODULE, 'addon', 'Unbound', 'TransmogSetExpansions.lua')

LABELS = {'CLASSIC': 0, 'TBC': 1, 'WOTLK': 2}
NAMES = {1: 'The Burning Crusade', 2: 'Wrath of the Lich King'}


def level_expansion(required_level):
    return 0 if required_level <= 60 else 1 if required_level <= 70 else 2


def read_sets(path):
    """[(id, name, label, [item ids])] in the file's order."""
    text = open(path, encoding='utf-8').read()
    sets = []
    for block in re.split(r'\n    \{\n', text)[1:]:
        set_id = re.search(r'\bid = "([^"]+)"', block).group(1)
        name = re.search(r'\bname = "([^"]*)"', block).group(1)
        label = re.search(r'\bexpansion = "([^"]*)"', block).group(1)
        pieces = [int(x) for x in re.findall(r'\{ slot = \d+, id = (\d+)', block)]
        sets.append((set_id, name, label, pieces))
    if not sets:
        raise RuntimeError(f'no sets found in {path}')
    return sets


def lua_string(text):
    return '"' + text.replace('\\', '\\\\').replace('"', '\\"') + '"'


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--mysql', default=os.path.join(ROOT, 'deps', 'mysql-8.4.11-winx64', 'bin', 'mysql.exe'))
    ap.add_argument('--sets', default=SET_DATA, help="mod-transmog-plus's set_data.lua")
    ap.add_argument('--user', default='acore')
    ap.add_argument('--password', default='acore')
    ap.add_argument('--host', default='127.0.0.1')
    ap.add_argument('--port', default='3306')
    ap.add_argument('--database', default='acore_world')
    args = ap.parse_args()

    sets = read_sets(args.sets)
    items = sorted({item for _, _, _, pieces in sets for item in pieces})
    out = subprocess.run([args.mysql, f'--user={args.user}', f'--password={args.password}', f'--host={args.host}',
                          f'--port={args.port}', '--batch', '--skip-column-names', args.database, '-e',
                          'SELECT entry, RequiredLevel FROM item_template WHERE entry IN (%s)' % ','.join(map(str, items))],
                         capture_output=True, text=True, check=True).stdout
    required = {int(a): int(b) for a, b in (line.split('\t') for line in out.splitlines() if line)}

    missing = [item for item in items if item not in required]
    if missing:
        print(f'{len(missing)} set pieces are not in item_template (ignored): {missing[:10]}')

    lines = []
    counts = {0: 0, 1: 0, 2: 0}
    for set_id, name, label, pieces in sets:
        expansion = max([LABELS.get(label, 0)] + [level_expansion(required[p]) for p in pieces if p in required])
        counts[expansion] += 1
        if expansion:
            lines.append(f'    [{lua_string(set_id)}] = {expansion}, -- {name} ({label})')

    with open(OUTPUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('-- Generated by tools/transmog_set_expansions.py - run it again instead of editing this file.\n')
        f.write("-- The expansion of each set in the Transmog window's Sets tab past classic (1 The Burning Crusade,\n")
        f.write('-- 2 Wrath of the Lich King), by its pieces\' required level; a set not listed is classic.\n')
        f.write('UnboundTransmogSetExpansion = {\n')
        f.write('\n'.join(lines) + '\n')
        f.write('}\n')

    print(f'{len(sets)} sets: {counts[0]} classic, {counts[1]} {NAMES[1]}, {counts[2]} {NAMES[2]} -> {OUTPUT}')


if __name__ == '__main__':
    main()
