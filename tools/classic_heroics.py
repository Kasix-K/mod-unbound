"""
Heroic mode for classic (1-60) dungeons.

For every dungeon in HEROIC_DUNGEONS this generates data/sql/db-world/unbound_classic_heroics.sql,
which (when the worldserver applies it) makes a heroic copy of every creature spawned in that
dungeon and links it as the creature's difficulty_entry_1, the same way Blizzard made heroics:

  - entry          = original entry + HEROIC_ENTRY_OFFSET
  - level          = HEROIC_LEVEL .. HEROIC_LEVEL + LEVEL_SPREAD, keeping the creatures' relative order
  - health, damage = original modifiers x HEALTH_MULTIPLIER / DAMAGE_MULTIPLIER
  - loot, gold     = unchanged (same lootid)
  - spawns         = every creature and gameobject spawn on the map also spawns in heroic
  - AIName/ScriptName are cleared: the normal creature's AI and script are always used.

It also adds a level requirement for the heroic mode (dungeon_access_template). The heroic
difficulty itself (MapDifficulty.dbc, client and server) is generated by tools/custom_dbc.py from
the same list. Run both after changing this file:

  python tools/classic_heroics.py
  python tools/custom_dbc.py
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
MODULE = os.path.dirname(HERE)

HEROIC_ENTRY_OFFSET = 1000000
HEROIC_LEVEL = 60
LEVEL_SPREAD = 2
HEALTH_MULTIPLIER = 1.5
DAMAGE_MULTIPLIER = 1.5

# dungeon_access_template.id is a tinyint (max 255; ids up to 121 are taken): heroic rows use 200 + list index.
ACCESS_ID_BASE = 200

# (map id, name). MapDifficulty IDs are 10000 + map id. Only append to this list (the order sets access ids).
HEROIC_DUNGEONS = [
    (34, 'Stormwind Stockades'),
]


def map_difficulty_id(map_id):
    return 10000 + map_id


def dungeon_sql(index, map_id, name):
    lines = [
        f'-- {name} (map {map_id})',
        f'SET @MAP := {map_id};',
        'DROP TEMPORARY TABLE IF EXISTS `unbound_hc_base`;',
        'CREATE TEMPORARY TABLE `unbound_hc_base` SELECT DISTINCT `id` AS `entry` FROM `creature` WHERE `map` = @MAP;',
        '-- leave creatures that already have a heroic version of their own alone',
        'DELETE `b` FROM `unbound_hc_base` `b` JOIN `creature_template` `ct` ON `ct`.`entry` = `b`.`entry`',
        '    WHERE `ct`.`difficulty_entry_1` NOT IN (0, `b`.`entry` + @OFFSET);',
        '-- and creatures also spawned on other maps: their heroic copy would show up in those maps\' heroics too',
        'DELETE `b` FROM `unbound_hc_base` `b` JOIN `creature` `c` ON `c`.`id` = `b`.`entry` AND `c`.`map` <> @MAP;',
        'SET @MINL := (SELECT MIN(`ct`.`minlevel`) FROM `creature_template` `ct` JOIN `unbound_hc_base` `b` ON `b`.`entry` = `ct`.`entry`);',
        'SET @SPAN := GREATEST((SELECT MAX(`ct`.`maxlevel`) FROM `creature_template` `ct` JOIN `unbound_hc_base` `b` ON `b`.`entry` = `ct`.`entry`) - @MINL, 1);',
        '',
        'DELETE FROM `creature_template` WHERE `entry` IN (SELECT `entry` + @OFFSET FROM `unbound_hc_base`);',
        'DROP TEMPORARY TABLE IF EXISTS `unbound_hc_tmp`;',
        'CREATE TEMPORARY TABLE `unbound_hc_tmp` SELECT `ct`.* FROM `creature_template` `ct` JOIN `unbound_hc_base` `b` ON `b`.`entry` = `ct`.`entry`;',
        'UPDATE `unbound_hc_tmp` SET `entry` = `entry` + @OFFSET,',
        '    `difficulty_entry_1` = 0, `difficulty_entry_2` = 0, `difficulty_entry_3` = 0, `AIName` = \'\', `ScriptName` = \'\',',
        '    `minlevel` = @LEVEL + ROUND((`minlevel` - @MINL) * @SPREAD / @SPAN),',
        '    `maxlevel` = @LEVEL + ROUND((`maxlevel` - @MINL) * @SPREAD / @SPAN),',
        '    `HealthModifier` = `HealthModifier` * @HEALTH, `DamageModifier` = `DamageModifier` * @DAMAGE, `VerifiedBuild` = 0;',
        'INSERT INTO `creature_template` SELECT * FROM `unbound_hc_tmp`;',
        'UPDATE `creature_template` `ct` JOIN `unbound_hc_base` `b` ON `b`.`entry` = `ct`.`entry` SET `ct`.`difficulty_entry_1` = `b`.`entry` + @OFFSET;',
    ]
    # Per-creature tables the heroic copy needs its own rows in.
    for table, column in (('creature_template_model', 'CreatureID'), ('creature_template_addon', 'entry'),
                          ('creature_template_spell', 'CreatureID'), ('creature_template_movement', 'CreatureId'),
                          ('creature_template_resistance', 'CreatureID')):
        lines += [
            f'DELETE FROM `{table}` WHERE `{column}` IN (SELECT `entry` + @OFFSET FROM `unbound_hc_base`);',
            'DROP TEMPORARY TABLE IF EXISTS `unbound_hc_tmp`;',
            f'CREATE TEMPORARY TABLE `unbound_hc_tmp` SELECT `t`.* FROM `{table}` `t` JOIN `unbound_hc_base` `b` ON `b`.`entry` = `t`.`{column}`;',
            f'UPDATE `unbound_hc_tmp` SET `{column}` = `{column}` + @OFFSET;',
            f'INSERT INTO `{table}` SELECT * FROM `unbound_hc_tmp`;',
        ]
    lines += [
        '',
        '-- spawn everything in heroic too (spawnMask bit 1 = normal, bit 2 = heroic)',
        'UPDATE `creature` SET `spawnMask` = `spawnMask` | 2 WHERE `map` = @MAP;',
        'UPDATE `gameobject` SET `spawnMask` = `spawnMask` | 2 WHERE `map` = @MAP;',
        '',
        f'DELETE FROM `dungeon_access_template` WHERE `map_id` = @MAP AND `difficulty` = 1;',
        'INSERT INTO `dungeon_access_template` (`id`, `map_id`, `difficulty`, `min_level`, `max_level`, `min_avg_item_level`, `comment`) VALUES',
        f"({ACCESS_ID_BASE + index}, @MAP, 1, @LEVEL, 0, 0, '{name} (Heroic)');",
        'DROP TEMPORARY TABLE IF EXISTS `unbound_hc_tmp`;',
        'DROP TEMPORARY TABLE IF EXISTS `unbound_hc_base`;',
    ]
    return '\n'.join(lines)


def main():
    head = [
        '-- Generated by tools/classic_heroics.py - edit the settings there, not this file.',
        f'SET @OFFSET := {HEROIC_ENTRY_OFFSET};',
        f'SET @LEVEL  := {HEROIC_LEVEL};',
        f'SET @SPREAD := {LEVEL_SPREAD};',
        f'SET @HEALTH := {HEALTH_MULTIPLIER};',
        f'SET @DAMAGE := {DAMAGE_MULTIPLIER};',
    ]
    body = [dungeon_sql(i, map_id, name) for i, (map_id, name) in enumerate(HEROIC_DUNGEONS)]
    path = os.path.join(MODULE, 'data', 'sql', 'db-world', 'unbound_classic_heroics.sql')
    with open(path, 'w', encoding='utf8', newline='\n') as f:
        f.write('\n'.join(head) + '\n\n' + '\n\n'.join(body) + '\n')
    print('wrote', path, f'({len(HEROIC_DUNGEONS)} dungeons)')


if __name__ == '__main__':
    main()
