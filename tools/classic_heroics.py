"""
Heroic mode for classic (1-60) dungeons.

For every dungeon in HEROIC_DUNGEONS this generates data/sql/db-world/unbound_classic_heroics.sql,
which (when the worldserver applies it) makes a heroic copy of every creature spawned in that
dungeon and links it as the creature's difficulty_entry_1, the same way Blizzard made heroics:

  - entry          = original entry + HEROIC_ENTRY_OFFSET
  - level          = HEROIC_LEVEL .. HEROIC_LEVEL + LEVEL_SPREAD, keeping the creatures' relative order
  - health, damage = original modifiers x HEALTH_MULTIPLIER / DAMAGE_MULTIPLIER
  - loot, gold     = unchanged (same lootid)
  - spawns         = every creature and gameobject spawn on the map also spawns in heroic
  - AIName/ScriptName are cleared: the normal creature's AI and script are always used.

It also adds a level requirement for the heroic mode (dungeon_access_template). The heroic
difficulty itself (MapDifficulty.dbc, client and server) is generated by tools/custom_dbc.py from
the same list. Heroic bosses' own loot tables and gold come from tools/heroic_loot.py. Run both after
changing this file:

  python tools/classic_heroics.py
  python tools/custom_dbc.py
"""
