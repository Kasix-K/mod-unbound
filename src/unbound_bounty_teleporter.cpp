/*
 * mod-unbound: the Bounty Wayfinder (creature 190211), beside every Bulletin Board.
 *
 * Its menu lists the Bulletin Board's open-world quests the player has in their quest log first (daily kill
 * bounties, the weekly elite bounty), then "All bounty destinations". Choosing one drops the player high in the
 * air near that quest's targets, outside every hostile creature's aggro range, with Wayfinder's Descent (spell
 * 200204, a slow fall that can't be cancelled): they see the camp from above and glide in. The descent is kept
 * up until they land and removed then. Camps in caves or tunnels teleport to a ground spot instead. The spots
 * are in the world table `unbound_bounty_teleports`, generated by tools/bounty_teleporter.py (which also
 * explains how they were chosen), and loaded at startup.
 */

#include "Chat.h"
#include "Creature.h"
#include "DatabaseEnv.h"
#include "Player.h"
#include "ScriptMgr.h"
#include "ScriptedGossip.h"

#include <algorithm>
#include <string>
#include <unordered_map>
#include <vector>

namespace
{
    constexpr uint32 NPC_TEXT_WAYFINDER = 190211;   // npc_text, in unbound_bounty_teleporter.sql
    constexpr uint32 ACTION_SHOW_ALL = 1;           // quest ids (the other actions) are much larger
    constexpr uint32 SPELL_WAYFINDERS_DESCENT = 200204;   // tools/custom_dbc.py: Slow Fall, can't be cancelled
    constexpr uint32 DESCENT_LAND_GRACE_MS = 2000;  // after arriving, wait this long before checking for landing
    constexpr uint32 DESCENT_MAX_MS = 5 * MINUTE * IN_MILLISECONDS;   // give up (remove it) after this long

    struct BountyTeleport
    {
        uint32 quest;
        std::string label;   // "Name (Zone)"
        uint32 map;
        float x, y, z, o;
        bool drop;            // arrive in the air at dropX/Y/Z with the slow fall, not on the ground spot
        float dropX, dropY, dropZ;
    };

    // players on their way down: milliseconds since they arrived (0 = still teleporting)
    std::unordered_map<ObjectGuid, uint32> sDescending;

    std::vector<BountyTeleport> sTeleports;

    void LoadTeleports()
    {
        sTeleports.clear();
        QueryResult result = WorldDatabase.Query("SELECT `quest`, `name`, `zone`, `map`, `x`, `y`, `z`, `o`, `drop`, "
                                                 "`drop_x`, `drop_y`, `drop_z` FROM `unbound_bounty_teleports` "
                                                 "ORDER BY `quest`");
        if (!result)
            return;

        do
        {
            Field* f = result->Fetch();
            sTeleports.push_back({ f[0].Get<uint32>(), f[1].Get<std::string>() + " (" + f[2].Get<std::string>() + ")",
                                   f[3].Get<uint16>(), f[4].Get<float>(), f[5].Get<float>(), f[6].Get<float>(),
                                   f[7].Get<float>(), f[8].Get<uint8>() != 0, f[9].Get<float>(), f[10].Get<float>(),
                                   f[11].Get<float>() });
        } while (result->NextRow());
    }

    BountyTeleport const* FindTeleport(uint32 quest)
    {
        for (BountyTeleport const& t : sTeleports)
            if (t.quest == quest)
                return &t;
        return nullptr;
    }

    bool HasQuestInLog(Player* player, uint32 quest)
    {
        QuestStatus status = player->GetQuestStatus(quest);
        return status == QUEST_STATUS_INCOMPLETE || status == QUEST_STATUS_COMPLETE;
    }
}

class unbound_bounty_teleporter_world : public WorldScript
{
public:
    unbound_bounty_teleporter_world() : WorldScript("unbound_bounty_teleporter_world", { WORLDHOOK_ON_STARTUP }) { }

    void OnStartup() override
    {
        LoadTeleports();
        LOG_INFO("module", ">> mod-unbound: loaded {} Bounty Wayfinder destinations", sTeleports.size());
    }
};

class npc_unbound_bounty_wayfinder : public CreatureScript
{
public:
    npc_unbound_bounty_wayfinder() : CreatureScript("npc_unbound_bounty_wayfinder") { }

    bool OnGossipHello(Player* player, Creature* creature) override
    {
        ClearGossipMenuFor(player);
        for (BountyTeleport const& t : sTeleports)
            if (HasQuestInLog(player, t.quest))
                AddGossipItemFor(player, GOSSIP_ICON_TAXI, "Your bounty: " + t.label, GOSSIP_SENDER_MAIN, t.quest);
        AddGossipItemFor(player, GOSSIP_ICON_CHAT, "All bounty destinations", GOSSIP_SENDER_MAIN, ACTION_SHOW_ALL);
        SendGossipMenuFor(player, NPC_TEXT_WAYFINDER, creature->GetGUID());
        return true;
    }

    bool OnGossipSelect(Player* player, Creature* creature, uint32 /*sender*/, uint32 action) override
    {
        if (action == ACTION_SHOW_ALL)
        {
            ClearGossipMenuFor(player);
            for (BountyTeleport const& t : sTeleports)
                AddGossipItemFor(player, GOSSIP_ICON_TAXI, t.label, GOSSIP_SENDER_MAIN, t.quest);
            SendGossipMenuFor(player, NPC_TEXT_WAYFINDER, creature->GetGUID());
            return true;
        }

        CloseGossipMenuFor(player);
        BountyTeleport const* t = FindTeleport(action);
        if (!t)
            return true;

        if (player->IsInCombat())
        {
            ChatHandler(player->GetSession()).SendSysMessage("You can't be teleported while in combat.");
            return true;
        }

        if (t->drop)
        {
            sDescending[player->GetGUID()] = 0;
            player->TeleportTo(t->map, t->dropX, t->dropY, t->dropZ, t->o);
        }
        else
            player->TeleportTo(t->map, t->x, t->y, t->z, t->o);
        return true;
    }
};

// Wayfinder's Descent: on once the player has arrived, kept up while they fall, removed when they land.
class unbound_bounty_teleporter_player : public PlayerScript
{
public:
    unbound_bounty_teleporter_player() : PlayerScript("unbound_bounty_teleporter_player", {
        PLAYERHOOK_ON_LOGIN,
        PLAYERHOOK_ON_LOGOUT,
        PLAYERHOOK_ON_UPDATE
    }) { }

    void OnPlayerLogin(Player* player) override
    {
        player->RemoveAurasDueToSpell(SPELL_WAYFINDERS_DESCENT); // never left over from a logout mid-fall
    }

    void OnPlayerLogout(Player* player) override
    {
        sDescending.erase(player->GetGUID());
    }

    void OnPlayerUpdate(Player* player, uint32 diff) override
    {
        if (sDescending.empty())
            return;

        auto itr = sDescending.find(player->GetGUID());
        if (itr == sDescending.end() || player->IsBeingTeleported() || !player->IsInWorld())
            return;

        uint32& elapsed = itr->second;
        bool const justArrived = elapsed == 0;
        elapsed += std::max<uint32>(diff, 1);

        bool const landed = !justArrived && elapsed > DESCENT_LAND_GRACE_MS && !player->IsFalling();
        if (landed || !player->IsAlive() || elapsed > DESCENT_MAX_MS)
        {
            player->RemoveAurasDueToSpell(SPELL_WAYFINDERS_DESCENT);
            sDescending.erase(itr);
            return;
        }

        if (!player->HasAura(SPELL_WAYFINDERS_DESCENT)) // on arrival, and again if its 2 minutes run out mid-air
            player->AddAura(SPELL_WAYFINDERS_DESCENT, player);
    }
};

void AddSC_unbound_bounty_teleporter()
{
    new unbound_bounty_teleporter_world();
    new npc_unbound_bounty_wayfinder();
    new unbound_bounty_teleporter_player();
}
